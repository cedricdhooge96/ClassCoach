-- Builds ClassCoach/Data/TalentLinks.lua from Zbuilds' data file.
--
--   curl -sL https://raw.githubusercontent.com/Zael98/Zbuilds/main/Data.lua -o /tmp/zbuilds-data.lua
--   lua5.1 tools/talentlinks.lua /tmp/zbuilds-data.lua > ClassCoach/Data/TalentLinks.lua
--   tests/run.sh talents      (every build link of every profile must still read cleanly)
--
-- Zbuilds (github.com/Zael98/Zbuilds, MIT License, Copyright (c) 2026 Zael98) reads
-- the guide sites' talent calculators and keeps, per site, which talent each link
-- symbol stands for (decoders.<site>[CLASS][symbol] = { tree, index }). This turns
-- those into talent names. The data file is run with nothing in reach (no io, no os):
-- it only builds a table.
local path = arg and arg[1]
if not path then
  io.stderr:write("usage: lua5.1 tools/talentlinks.lua <Zbuilds Data.lua>\n")
  os.exit(2)
end
local chunk = assert(loadfile(path))
local sandbox = {}
setfenv(chunk, sandbox)
chunk()
local data = assert(sandbox.ZbuildsData, "no ZbuildsData in " .. path)

local SITES = { { "iv", "Icy Veins" }, { "tavern", "Warcraft Tavern" } }
local CLASSES = { "WARRIOR", "PALADIN", "HUNTER", "ROGUE", "PRIEST", "SHAMAN", "MAGE", "WARLOCK", "DRUID" }
local WIDTH = 140

local function quote(s) return ("%q"):format(s) end

local out = {}
local function line(s) out[#out + 1] = s end
line([[-- How the talent calculators of two guide sites spell a build in a link, for]])
line([[-- WoW Forever's talents. Each symbol stands for one talent; a link lists one]])
line([[-- symbol per talent point, in the order the points are taken.]])
line([[--]])
line("--   Icy Veins        icy-veins.com/wow-forever/<class>-talent-calculator#tc-<symbols>[~version]")
line([[--   Warcraft Tavern  warcrafttavern.com/forever/tools/talent-calculator/<class>#?t=<tree letter><symbols>...]])
line([[--]])
line([[-- ClassCoach turns the symbols into talent NAMES here and finds each name in]])
line([[-- your own talent window, so a link keeps working when the game moves a talent.]])
line([[-- A link that names a talent your game does not have is refused, never guessed.]])
line([[--]])
line([[-- The symbol tables come from Zbuilds (github.com/Zael98/Zbuilds, MIT License,]])
line([[-- Copyright (c) 2026 Zael98), which reads them from the sites' calculators.]])
line(("-- Generated by tools/talentlinks.lua from its data of %s; do not edit by hand."):format(
  tostring(data.generated or "?"):sub(1, 10)))
line([[local _, ns = ...]])
line("")
line([[ns.TalentLinks = {]])
for _, site in ipairs(SITES) do
  local key, name = site[1], site[2]
  local decoders = assert(data.decoders and data.decoders[key], "no decoders for " .. key)
  line("  -- " .. name)
  line("  " .. key .. " = {")
  for _, class in ipairs(CLASSES) do
    local map, trees = decoders[class], data.classes[class] and data.classes[class].trees
    if map and trees then
      local entries = {}
      for symbol, at in pairs(map) do
        local tree = trees[at[1]]
        local talent = tree and tree.talents and tree.talents[at[2]]
        if talent and talent.name then entries[#entries + 1] = { symbol = symbol, tree = at[1], index = at[2], name = talent.name } end
      end
      table.sort(entries, function(a, b)
        if a.tree ~= b.tree then return a.tree < b.tree end
        if a.index ~= b.index then return a.index < b.index end
        return a.symbol < b.symbol
      end)
      line("    " .. class .. " = {")
      local current = "     "
      for _, e in ipairs(entries) do
        local item = " [" .. quote(e.symbol) .. "] = " .. quote(e.name) .. ","
        if #current + #item > WIDTH then
          line(current)
          current = "     "
        end
        current = current .. item
      end
      if current ~= "     " then line(current) end
      line("    },")
    end
  end
  line("  },")
end
line("}")
io.write(table.concat(out, "\n"), "\n")
